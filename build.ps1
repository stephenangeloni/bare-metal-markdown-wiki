$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot
$kb = (Resolve-Path 'articles').Path
$out = Join-Path $PWD 'data.js'
$epoch = [datetime]::new(1970,1,1,0,0,0,[System.DateTimeKind]::Utc)
$entries = @()
foreach ($f in (Get-ChildItem -LiteralPath $kb -Recurse -File -Filter '*.md' | Sort-Object FullName)) {
  $rel = $f.FullName.Substring($kb.Length + 1).Replace('\', '/')
  $slug = $rel.Substring(0, $rel.Length - 3)
  $mt = [int][Math]::Floor(($f.LastWriteTimeUtc - $epoch).TotalSeconds)
  $b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($f.FullName))
  $slugQ = $slug.Replace('\', '\\').Replace('"', '\"')
  $entries += '  {slug:"' + $slugQ + '", mtime:' + $mt + ', content:"' + $b64 + '"}'
}
$ps = New-Object System.Text.StringBuilder
[void]$ps.AppendLine('/* generated by build.ps1 - offline snapshot of articles/ */')
[void]$ps.AppendLine('window.PAGES_BUNDLED=[')
[void]$ps.AppendLine(($entries -join ",`n"))
[void]$ps.AppendLine('];')
[IO.File]::WriteAllText($out, $ps.ToString())
Write-Host "Wrote data.js ($($entries.Count) pages)"
