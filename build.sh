#!/usr/bin/env bash
# Offline snapshot of articles/ -> data.js. No network, no server.
# Usage: ./build.sh   (or: bash build.sh)
set -euo pipefail
cd "$(dirname "$0")"

KB="articles"
OUT="data.js"

if [ ! -d "$KB" ]; then
  echo "No '$KB/' folder here — nothing to build." >&2
  exit 1
fi

# emit a double-quoted JS string from $1 (escape backslash, then double-quote)
json_str() { printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"; }

{
  echo "/* generated by build.sh — offline snapshot of $KB/ */"
  echo "window.PAGES_BUNDLED=["
  first=1
  while IFS= read -r -d '' f; do
    rel="${f#"$KB"/}"
    slug="${rel%.md}"
    mt="$(date -r "$f" +%s 2>/dev/null || stat -c %Y "$f")"
    b64="$(base64 < "$f" | tr -d '\n')"
    [ "$first" -eq 1 ] || printf ',\n'
    first=0
    printf '  {slug:%s, mtime:%s, content:"%s"}' "$(json_str "$slug")" "$mt" "$b64"
  done < <(find "$KB" -type f -name '*.md' -print0 | sort -z)
  printf '\n];\n'
} > "$OUT"

echo "Wrote $OUT ($(grep -c 'slug:' "$OUT" 2>/dev/null || echo 0) pages)"
